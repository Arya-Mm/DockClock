// Generates docs/postman/*.json from the real route files, so the collection lists every endpoint (PLAN §6.6 D8).
// "Smoke" requests are read-only and must return 2xx against a running local stack.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, sep } from "node:path";

const API = "apps/web/app/api";
const files: string[] = [];
const walk = (d: string) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (f === "route.ts") files.push(p); } };
walk(API);

// Example bodies for the write routes (ids are collection variables).
const BODY: Record<string, unknown> = {
  "POST /loads": { facilityId: "{{facilityId}}" }, "POST /loads/:id/hold": { useVault: true },
  "POST /loads/:id/evidence": { source: "YARD_GATE_SYSTEM", kind: "ARRIVAL", utcAt: "{{nowIso}}", citation: "Gate ARRIVAL" },
  "POST /loads/:id/offers": { kind: "SLOT_SWAP_WITH_CREDIT" }, "POST /loads/:id/refund": { reason: "GOODWILL" },
  "POST /agents/negotiate": { loadId: "{{loadId}}" }, "POST /cockpit/review/:loadId": { decision: "APPROVE" },
  "POST /dock/preview": { loadId: "{{loadId}}", endMs: 1800000000000 }, "POST /offers/:id/accept": { version: 1, planHash: "{{planHash}}" },
  "POST /driver/:id/offers/:offerId": { decision: "ACCEPT", version: 1, planHash: "{{planHash}}" }, "POST /driver/:id/parts": { productId: "{{productId}}" },
  "POST /driver/:id/checkin": {}, "POST /ops/login": { key: "{{opsKey}}" }, "POST /paypal/orders/:orderId/authorize": { loadId: "{{loadId}}" },
};
const SMOKE = new Set(["GET /health", "GET /agents/verify", "GET /loads", "GET /cockpit/:dataset"]);
const VARS: Record<string, string> = { id: "{{loadId}}", loadId: "{{loadId}}", dataset: "ledger", orderId: "{{orderId}}", offerId: "{{offerId}}", job: "tick" };

const items = files.sort().flatMap((f) => {
  const src = readFileSync(f, "utf8");
  const route = "/" + relative(API, f).split(sep).slice(0, -1).join("/").replace(/\[(\w+)\]/g, ":$1");
  return [...src.matchAll(/export (?:const|async function) (GET|POST|PUT|PATCH|DELETE)\b/g)].map((m) => {
    const method = m[1]!, key = `${method} ${route}`, body = BODY[key], smoke = SMOKE.has(key);
    const path = route.replace(/:(\w+)/g, (_, v: string) => VARS[v] ?? `{{${v}}}`);
    return { smoke, item: { name: key,
      request: { method, url: { raw: `{{baseUrl}}/api${path}`, host: ["{{baseUrl}}"], path: ["api", ...path.split("/").filter(Boolean)] },
        header: [{ key: "x-ops-key", value: "{{opsKey}}" }, ...(body ? [{ key: "content-type", value: "application/json" }] : [])],
        ...(body ? { body: { mode: "raw", raw: JSON.stringify(body, null, 2) } } : {}) },
      event: [{ listen: "test", script: { exec: [smoke ? "pm.test('2xx', () => pm.response.to.be.success);" : "pm.test('no server error', () => pm.expect(pm.response.code).to.be.below(500));"] } }] } };
  });
});

const collection = {
  info: { name: "DockClock API", schema: "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
    description: "Every DockClock endpoint, generated by scripts/postman.ts. PayPal sandbox only. Money-moving routes need x-ops-key. Run the Smoke folder first." },
  item: [{ name: "Smoke (read-only, must be 2xx)", item: items.filter((i) => i.smoke).map((i) => i.item) },
    { name: "All endpoints", item: items.filter((i) => !i.smoke).map((i) => i.item) }],
};
const env = { name: "DockClock local", values: [["baseUrl", "http://localhost:3000"], ["opsKey", ""], ["loadId", ""], ["facilityId", "F-CHI-01"], ["orderId", ""], ["offerId", ""], ["planHash", ""], ["productId", ""], ["nowIso", "2026-11-12T15:00:00Z"]].map(([key, value]) => ({ key, value, enabled: true })) };
mkdirSync("docs/postman", { recursive: true });
writeFileSync("docs/postman/dockclock.postman_collection.json", JSON.stringify(collection, null, 2));
writeFileSync("docs/postman/dockclock.local.postman_environment.json", JSON.stringify(env, null, 2));
console.log(`${items.length} requests (${items.filter((i) => i.smoke).length} smoke)`);
